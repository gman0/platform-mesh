package server

import (
	"encoding/json"
	"net/http"

	pmaccessproto "go.platform-mesh.io/protocol/access"
)

// VersionsHandler serves the unauthenticated /versions probe. PM-side
// operators GET this to discover which handshake versions this SDK
// accepts and pick the highest mutually-supported one before posting
// to /vN/access.
func VersionsHandler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Method != http.MethodGet && r.Method != http.MethodHead {
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusOK)
		if r.Method == http.MethodHead {
			return
		}
		_ = json.NewEncoder(w).Encode(pmaccessproto.VersionsResponse{
			Versions: pmaccessproto.SupportedVersions,
		})
	})
}
