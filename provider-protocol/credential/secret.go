package credential

import (
	"crypto/rand"
	"encoding/base64"
	"errors"
	"strings"
)

// secretBytes is the length of every random secret: 256 bits.
const secretBytes = 32

// b64 is base64url without padding, refusing non-canonical input.
var b64 = base64.RawURLEncoding.Strict()

// connectionSecretPrefix lets secret scanners recognise leaked Connection
// Secrets.
const connectionSecretPrefix = "pmc1_"

// ErrMalformedSecret is returned for text that isn't a Connection Secret.
var ErrMalformedSecret = errors.New("malformed Connection Secret")

// ConnectionSecret is the bearer credential of Control Calls, generated by
// the PM-side: pmc1_ and 256 random bits, base64url without padding. The
// zero value is invalid.
type ConnectionSecret struct {
	value string
}

// NewConnectionSecret returns a new, random Connection Secret.
func NewConnectionSecret() ConnectionSecret {
	return ConnectionSecret{value: connectionSecretPrefix + randomSecret()}
}

// ParseConnectionSecret parses a Connection Secret.
func ParseConnectionSecret(s string) (ConnectionSecret, error) {
	rest, ok := strings.CutPrefix(s, connectionSecretPrefix)
	if !ok || !validSecret(rest) {
		return ConnectionSecret{}, ErrMalformedSecret
	}
	return ConnectionSecret{value: s}, nil
}

// Reveal returns the secret value, to store it or send it as a bearer.
func (s ConnectionSecret) Reveal() string { return s.value }

// Hash returns the hash the Provider-side stores and compares against.
func (s ConnectionSecret) Hash() Hash { return hashOf(s.value) }

// IsZero reports whether s is the zero value.
func (s ConnectionSecret) IsZero() bool { return s.value == "" }

// String never shows the secret.
func (s ConnectionSecret) String() string { return redacted(s.IsZero()) }

// GoString never shows the secret.
func (s ConnectionSecret) GoString() string { return "credential.ConnectionSecret" + redacted(s.IsZero()) }

func randomSecret() string {
	b := make([]byte, secretBytes)
	_, _ = rand.Read(b) // never fails
	return b64.EncodeToString(b)
}

func validSecret(s string) bool {
	b, ok := decodeB64(s)
	return ok && len(b) == secretBytes
}

// decodeB64 decodes s and requires it to be the canonical encoding. The
// decoder alone skips \r and \n, even in strict mode.
func decodeB64(s string) ([]byte, bool) {
	b, err := b64.DecodeString(s)
	if err != nil || b64.EncodeToString(b) != s {
		return nil, false
	}
	return b, true
}

func redacted(zero bool) string {
	if zero {
		return "<empty>"
	}
	return "<redacted>"
}
